CREATE OR REPLACE FUNCTION public.admin_end_user_sessions(p_user_id uuid)
RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
DECLARE v_count integer;
BEGIN
  IF NOT public.is_admin() THEN RAISE EXCEPTION 'Not authorized'; END IF;
  IF (SELECT auth.jwt()->>'aal') IS DISTINCT FROM 'aal2' THEN RAISE EXCEPTION 'MFA required'; END IF;
  UPDATE public.user_sessions SET ended_at = now(), end_reason = 'admin'
  WHERE user_id = p_user_id AND ended_at IS NULL;
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END; $$;
REVOKE ALL ON FUNCTION public.admin_end_user_sessions(uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_end_user_sessions(uuid) TO authenticated;

-- Read-only security status for the Users tab (admins only)
CREATE OR REPLACE FUNCTION public.admin_get_user_security(p_user_id uuid)
RETURNS jsonb
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$
  SELECT CASE WHEN public.is_admin() AND (SELECT auth.jwt()->>'aal') = 'aal2' THEN
    (SELECT jsonb_build_object(
       'password_changed_at',   s.password_changed_at,
       'must_change_password',  s.must_change_password,
       'failed_login_attempts', s.failed_login_attempts,
       'locked_until',          s.locked_until,
       'locked_forever',        s.locked_forever,
       'last_login_at',         s.last_login_at,
       'active_sessions',       (SELECT COUNT(*) FROM public.user_sessions x
                                 WHERE x.user_id = s.user_id AND x.ended_at IS NULL)
     ) FROM public.user_security s WHERE s.user_id = p_user_id)
  ELSE NULL END;
$$;
REVOKE ALL ON FUNCTION public.admin_get_user_security(uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_get_user_security(uuid) TO authenticated;