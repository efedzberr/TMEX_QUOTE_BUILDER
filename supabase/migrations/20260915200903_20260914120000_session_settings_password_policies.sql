/*
  # Session Settings (per profile) and Password Policies (org-wide)

  Salesforce-style security settings for the Smart Pricing Hub.

  ## profiles
  - session_timeout_minutes: inactivity timeout per profile (15/30/60/120/240). Default 120.
    Editable on system profiles too, so a dedicated RPC `set_profile_session_timeout` is
    provided (the existing `profiles_update_admin` policy blocks is_system = true rows).

  ## New tables
  - password_policies  : single row (id = 1), org-wide. Readable by any aal2 user (the client
                         validates against it), writable by admins only.
  - user_security      : per-user state (password_changed_at, must_change_password, failed
                         attempts, lockout). NO direct client access; RPCs / service role only.
  - password_history   : bcrypt hashes of previous passwords (generated by our Edge Function,
                         Supabase never exposes its own hashes). NO direct client access.
  - user_sessions      : one row per app session; last_activity_at drives server-side timeout
                         enforcement. NO direct client access.

  ## RPCs (SECURITY DEFINER)
  - start_session()                       -> creates a session row, returns its id
  - touch_session(p_session_id)           -> refreshes last_activity_at; expires the session if
                                             inactivity exceeded the profile timeout
  - end_session(p_session_id, p_reason)   -> closes the session
  - is_session_valid(p_session_id)        -> boolean, for write RPCs to reject expired sessions
  - set_profile_session_timeout(id, mins) -> admin only
  - admin_unlock_user(user_id)            -> admin only
  - admin_force_password_change(user_id)  -> admin only
  - admin_end_user_sessions(user_id)      -> admin only

  ## Permission key
  - admin.password_policies granted to the Full Access system profile.

  No existing policy, table, function or trigger is dropped or modified.
*/

-- ============================================================
-- 1. profiles.session_timeout_minutes
-- ============================================================
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                 WHERE table_schema='public' AND table_name='profiles' AND column_name='session_timeout_minutes') THEN
    ALTER TABLE public.profiles
      ADD COLUMN session_timeout_minutes integer NOT NULL DEFAULT 120
      CHECK (session_timeout_minutes IN (15, 30, 60, 120, 240));
  END IF;
END $$;

CREATE OR REPLACE FUNCTION public.set_profile_session_timeout(p_profile_id uuid, p_minutes integer)
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  IF NOT public.is_admin() THEN RAISE EXCEPTION 'Not authorized'; END IF;
  IF (SELECT auth.jwt()->>'aal') IS DISTINCT FROM 'aal2' THEN RAISE EXCEPTION 'MFA required'; END IF;
  IF p_minutes NOT IN (15, 30, 60, 120, 240) THEN RAISE EXCEPTION 'Invalid session timeout'; END IF;
  UPDATE public.profiles SET session_timeout_minutes = p_minutes WHERE id = p_profile_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Profile not found'; END IF;
END; $$;
REVOKE ALL ON FUNCTION public.set_profile_session_timeout(uuid, integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.set_profile_session_timeout(uuid, integer) TO authenticated;

